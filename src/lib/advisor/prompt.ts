export function buildSystemInstruction(context: {
  profile?: string;
  notes?: string;
  knowledge?: string;
  topic?: string;
  extra?: string;
  trial?: { n: number; of: number };
}): string {
  const parts = [BASE];
  if (context.trial) {
    const last = context.trial.n >= context.trial.of;
    parts.push(
      `# تجربة مجانية: هذا السؤال رقم ${context.trial.n} من ${context.trial.of}\n` +
        `هذا تاجر بعده بالتجربة المجانية وعنده بس ${context.trial.of} أسئلة. خلي هذا الجواب أحسن جواب ممكن:\n` +
        `- خاص بمشروعه هو: استعمل كل شي تعرفه من ملفه ومن اللي كتبه بالكورس، وسمي منتجه وزبونه بكلامه.\n` +
        `- بيه شي ينفذه اليوم: حسبة بأرقامه، أو رسالة جاهزة بلوك script، أو تشخيص واضح لصورته إذا أرسل صورة.\n` +
        `- وين الحل الأعمق موجود بفصل أو حل بالكورس، أشر له مرة وحدة بشكل طبيعي ([[chapterX]] أو [[solution:...]]).\n` +
        `- لا تبيع: لا تذكر السعر ولا الاشتراك ولا عدد الأسئلة الباقية، الواجهة تتكفل بهذا.\n` +
        (last ? `- هذا آخر سؤال مجاني: اختم بخطوة وحدة واضحة ينفذها خلال 24 ساعة، بدون أسئلة متابعة.` : `- خلي اقتراحات المتابعة أسئلة تكمل نفس مشكلته، حتى يستفاد من باقي أسئلته.`)
    );
  }
  parts.push(
    context.profile
      ? `# ملف مشروع التاجر (معلومات مؤكدة منه، استعملها وخصص الجواب عليها)\n${context.profile}`
      : `# ملف مشروع التاجر\nفارغ لحد الآن. إذا السؤال يحتاج أرقام مشروعه، اسأله عنها بلطف (وسجلها بـ PROFILE من يذكرها).`
  );
  if (context.notes) {
    parts.push(
      `# اللي كتبه التاجر بنفسه بخطوات "طبقها على منتجك" بالكورس\nهذا كلامه عن منتجه وزبونه وعرضه. استعمله حتى تخصص الجواب، لا تسأله عن شي كتبه هنا، واذا تعارض ويا ملف المشروع اعتمد الأحدث اللي يكوله بالمحادثة.\n${context.notes}`
    );
  }
  if (context.knowledge) parts.push(`# مقتطفات من محتوى كورس فيزيون ذات صلة بالسؤال (استند عليها وأشر للفصل إذا تفيد)\n${context.knowledge}`);
  if (context.topic) parts.push(`# الموضوع المختار من الواجهة\n${context.topic}`);
  if (context.extra) parts.push(`# بيانات إضافية من أدوات المنصة\n${context.extra}`);
  return parts.join("\n\n");
}
